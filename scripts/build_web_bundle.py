def agents_json() -> str:
    """Every agent with its role, goal, tools and task prompt, read from the crews' YAML.

    The web app shows them on its Architecture page without importing crewai.
    """
    import yaml

    crews = []
    for folder, title in CREWS:
        base = SRC / "crews" / folder
        agents = yaml.safe_load((base / "config" / "agents.yaml").read_text(encoding="utf-8"))
        tasks = yaml.safe_load((base / "config" / "tasks.yaml").read_text(encoding="utf-8"))
        code = (base / f"{folder}.py").read_text(encoding="utf-8")
        tools = {m[0]: re.findall(r"(\w+)_tool", m[1]) for m in
                 re.findall(r'agents_config\["(\w+)"\].*?tools=\[([^\]]*)\]', code, re.S)}
        crews.append({"crew": folder, "title": title, "agents": [
            {"key": key, "role": a["role"].strip(), "goal": " ".join(a["goal"].split()),
             "tools": tools.get(key, []),
             "tasks": [{"key": t_key, "description": t["description"].strip(),
                        "expected_output": " ".join(t["expected_output"].split())}
                       for t_key, t in tasks.items() if t["agent"] == key]}
            for key, a in agents.items()]})
    return json.dumps(crews, indent=2, ensure_ascii=False) + "\n"


def source_json() -> str:
    files = [{"title": title, "path": path, "why": why,
              "language": "yaml" if path.endswith(".yaml") else "python",
              "content": (ROOT / path).read_text(encoding="utf-8")}
             for title, path, why in SOURCE_FILES]
    return json.dumps(files, indent=1, ensure_ascii=False) + "\n"


def _copy(src: Path, dst: Path) -> None:
    if src.is_dir():
        for child in sorted(src.iterdir()):
            if child.name not in SKIP:
                _copy(child, dst / child.name)
    else:
        dst.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(src, dst)


def build(out: Path) -> None:
    shutil.rmtree(out, ignore_errors=True)
    out.mkdir(parents=True)
    (out / "pyproject.toml").write_text(PYPROJECT, encoding="utf-8")
    (out / "app.py").write_text(ENTRYPOINT, encoding="utf-8")
    for name in CODE:
        _copy(SRC / name, out / "churn_pipeline" / name)
    # Vercel serves public/ from its CDN; Flask's static folder is not used there.
    _copy(SRC / "web" / "static", out / "public" / "static")
    for name in ARTIFACTS:
        _copy(ROOT / "artifacts" / name, out / "artifacts" / name)
    _copy(ROOT / "contracts" / "dataset_contract.lock.json", out / "contracts" / "dataset_contract.lock.json")


def snapshot(folder: Path) -> dict[str, bytes]:
    return {str(p.relative_to(folder)): p.read_bytes() for p in sorted(folder.rglob("*"))
            if p.is_file() and "__pycache__" not in p.parts}


def main(argv: list[str]) -> int:
    if "--check" in argv:
        import tempfile

        for path, content in ((AGENTS_JSON, agents_json), (SOURCE_JSON, source_json)):
            if not path.is_file() or path.read_text(encoding="utf-8") != content():
                print(f"{path.relative_to(ROOT)} is out of date")
                print("rebuild with: uv run python scripts/build_web_bundle.py")
                return 1

        with tempfile.TemporaryDirectory() as tmp:
            build(Path(tmp) / "web")
            expected, actual = snapshot(Path(tmp) / "web"), snapshot(BUNDLE) if BUNDLE.is_dir() else {}
        stale = sorted(k for k in expected.keys() | actual.keys() if expected.get(k) != actual.get(k))
        if stale:
            print(f"deploy/web is out of date ({len(stale)} files), for example: {stale[:5]}")
            print("rebuild with: uv run python scripts/build_web_bundle.py")
            return 1
        print("deploy/web is up to date")
        return 0
    AGENTS_JSON.write_text(agents_json(), encoding="utf-8")
    SOURCE_JSON.write_text(source_json(), encoding="utf-8")
    build(BUNDLE)
    files = snapshot(BUNDLE)
    print(f"deploy/web built: {len(files)} files, {sum(map(len, files.values())) / 1e6:.1f} MB")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
