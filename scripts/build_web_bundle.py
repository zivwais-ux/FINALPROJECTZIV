"""Build deploy/web/, the self-contained folder Vercel deploys.

The project's pyproject.toml pulls in crewai and the whole agent stack, far
more than the web app needs. deploy/web/ holds a light pyproject.toml, the
app's code (copied from src/), the reports it shows and the locked contract.

    uv run python scripts/build_web_bundle.py          # rebuild deploy/web/
    uv run python scripts/build_web_bundle.py --check  # exit 1 if it is out of date

Rebuild and commit after changing the app, the contract code or the artifacts;
tests/test_web_bundle.py fails while the folder is out of date.
"""
from __future__ import annotations

import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BUNDLE = ROOT / "deploy" / "web"
SRC = ROOT / "src" / "churn_pipeline"

CODE = ["__init__.py", "scenarios.py", "run_history.py", "contract", "web"]
ARTIFACTS = [
    "latest/validation_report.md", "latest/pipeline.log",
    "latest/crew1/clean_data.csv", "latest/crew1/dataset_contract.json", "latest/crew1/quality_report.json",
    "latest/crew1/quality_summary.md", "latest/crew1/insights.md", "latest/crew1/eda_report.html",
    "latest/crew2/evaluation_metrics.json", "latest/crew2/feature_spec.json",
    "latest/crew2/evaluation_report.md", "latest/crew2/model_card.md", "latest/crew2/model_approved.json",
    "latest/briefings", "broken",
]
SKIP = {"__pycache__", "crew1", "raw"}  # broken/<scenario>/crew1 holds data copies, not reports

PYPROJECT = """\
# Generated by scripts/build_web_bundle.py. Do not edit: change the source and rebuild.
[project]
name = "churn-pipeline-web"
version = "0.1.0"
description = "Web app of the churn pipeline: results and contract checker, no LLM"
requires-python = ">=3.12"
dependencies = [
    "flask>=3.1",
    "markdown>=3.11",
    "numpy>=2.0",
    "pandas>=2.3",
    "pydantic>=2.0",
]
"""

ENTRYPOINT = '''\
"""Vercel entrypoint. Generated by scripts/build_web_bundle.py. Do not edit."""
from pathlib import Path

from churn_pipeline.web.app import create_app

HERE = Path(__file__).resolve().parent
app = create_app(HERE / "artifacts", HERE / "contracts" / "dataset_contract.lock.json")
'''


def _copy(src: Path, dst: Path) -> None:
    if src.is_dir():
        for child in sorted(src.iterdir()):
            if child.name not in SKIP:
                _copy(child, dst / child.name)
    else:
        dst.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(src, dst)


def build(out: Path) -> None:
    shutil.rmtree(out, ignore_errors=True)
    out.mkdir(parents=True)
    (out / "pyproject.toml").write_text(PYPROJECT, encoding="utf-8")
    (out / "app.py").write_text(ENTRYPOINT, encoding="utf-8")
    for name in CODE:
        _copy(SRC / name, out / "churn_pipeline" / name)
    # Vercel serves public/ from its CDN; Flask's static folder is not used there.
    _copy(SRC / "web" / "static", out / "public" / "static")
    for name in ARTIFACTS:
        _copy(ROOT / "artifacts" / name, out / "artifacts" / name)
    _copy(ROOT / "contracts" / "dataset_contract.lock.json", out / "contracts" / "dataset_contract.lock.json")


def snapshot(folder: Path) -> dict[str, bytes]:
    return {str(p.relative_to(folder)): p.read_bytes() for p in sorted(folder.rglob("*"))
            if p.is_file() and "__pycache__" not in p.parts}


def main(argv: list[str]) -> int:
    if "--check" in argv:
        import tempfile

        with tempfile.TemporaryDirectory() as tmp:
            build(Path(tmp) / "web")
            expected, actual = snapshot(Path(tmp) / "web"), snapshot(BUNDLE) if BUNDLE.is_dir() else {}
        stale = sorted(k for k in expected.keys() | actual.keys() if expected.get(k) != actual.get(k))
        if stale:
            print(f"deploy/web is out of date ({len(stale)} files), for example: {stale[:5]}")
            print("rebuild with: uv run python scripts/build_web_bundle.py")
            return 1
        print("deploy/web is up to date")
        return 0
    build(BUNDLE)
    files = snapshot(BUNDLE)
    print(f"deploy/web built: {len(files)} files, {sum(map(len, files.values())) / 1e6:.1f} MB")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
